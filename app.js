// 3. DATA STORAGE LAYER (Cloud Firestore + Local Fallback)
// ============================================================================

const JournalStorage = {
  /**
   * Subscribes to real-time updates from Cloud Firestore.
   * Returns the unsubscribe function.
   */
  subscribe(onUpdate) {
    if (db) {
      const authUid = currentUser ? currentUser.uid : null;
      console.log(
        `%c[Firestore READ]%c Subscribing on path: /${CONFIG.COLLECTION_NAME} | Project: ${firebaseConfig.projectId} | Auth: ${authUid ? `Signed in (${authUid})` : "Unauthenticated (null)"}`,
        "color: #2b6c4b; font-weight: bold;",
        "color: inherit;"
      );

      return db.collection(CONFIG.COLLECTION_NAME).onSnapshot(
        (snapshot) => {
          const entries = [];
          snapshot.forEach((doc) => {
            entries.push({ id: doc.id, ...doc.data() });
          });

          // Sort chronologically by timestamp
          entries.sort((a, b) => new Date(a.timestamp) - new Date(b.timestamp));

          // Keep localStorage updated as cache
          this.setLocalEntries(entries);

          onUpdate(entries);
        },
        (error) => {
          console.error(
            `%c[Firestore READ ERROR]%c Failed operation on path: /${CONFIG.COLLECTION_NAME}\n` +
            `  • Operation: onSnapshot (query / collection read)\n` +
            `  • Target Path: /${CONFIG.COLLECTION_NAME}\n` +
            `  • Firebase ProjectId: ${firebaseConfig.projectId}\n` +
            `  • Current Auth State: ${currentUser ? `Signed in (UID: ${currentUser.uid})` : "NULL (Unauthenticated)"}\n` +
            `  • Error Code: ${error.code}\n` +
            `  • Error Message: ${error.message}`,
            "color: #a23b2a; font-weight: bold;",
            "color: inherit;"
          );

          if (error.code === "permission-denied") {
            showFeedback(
              "Firestore Notice: Permission denied on path /entries. Please check that you are signed in and your Firestore rules allow access.",
              "error"
            );
          }
          // Fall back to local storage
          onUpdate(this.getLocalEntries());
        }
      );
    } else {
      onUpdate(this.getLocalEntries());
      return () => {};
    }
  },

  /**
   * Saves a new turn entry to Cloud Firestore.
   * Format: { name, question, answer, nextQuestion, timestamp, userId, userPhoto }
   */
  async saveEntry(entry) {
    if (db) {
      const authUid = currentUser ? currentUser.uid : null;
      console.log(
        `%c[Firestore CREATE]%c Writing document to path: /${CONFIG.COLLECTION_NAME}/{autoId}\n` +
        `  • Operation: collection.add (CREATE only - does not update or write separate documents)\n` +
        `  • Target Path: /${CONFIG.COLLECTION_NAME}/{autoGeneratedDocId}\n` +
        `  • Firebase ProjectId: ${firebaseConfig.projectId}\n` +
        `  • Auth UID: ${authUid || "NULL"}\n` +
        `  • Document Payload:`,
        "color: #2b6c4b; font-weight: bold;",
        "color: inherit;",
        entry
      );

      try {
        const docRef = await db.collection(CONFIG.COLLECTION_NAME).add(entry);
        console.log(`%c[Firestore CREATE SUCCESS]%c Created document at /${CONFIG.COLLECTION_NAME}/${docRef.id}`, "color: #2b6c4b; font-weight: bold;", "color: inherit;");
        return { success: true };
      } catch (error) {
        console.error(
          `%c[Firestore WRITE ERROR]%c Failed operation on path: /${CONFIG.COLLECTION_NAME}/{autoId}\n` +
          `  • Operation: collection.add (CREATE)\n` +
          `  • Target Path: /${CONFIG.COLLECTION_NAME}/{newDocId}\n` +
          `  • Firebase ProjectId: ${firebaseConfig.projectId}\n` +
          `  • Current Auth State: ${currentUser ? `Signed in (UID: ${currentUser.uid})` : "NULL (Unauthenticated)"}\n` +
          `  • Error Code: ${error.code}\n` +
          `  • Error Message: ${error.message}`,
          "color: #a23b2a; font-weight: bold;",
          "color: inherit;"
        );

        return {
          success: false,
          error: error.code === "permission-denied"
            ? "Permission denied when saving to /entries. Confirm that your Firestore rules allow 'create' for signed-in users."
            : (error.message || "Could not save to database.")
        };
      }
    }

    // Fallback: save to localStorage if db unavailable
    try {
      const entries = this.getLocalEntries();
      entries.push(entry);
      this.setLocalEntries(entries);
      return { success: true };
    } catch (e) {
      return { success: false, error: e.message };
    }
  },

  getLocalEntries() {
    try {
      const raw = localStorage.getItem(CONFIG.STORAGE_KEY);
      return raw ? JSON.parse(raw) : [];
    } catch {
      return [];
    }
  },

  setLocalEntries(entries) {
    try {
      localStorage.setItem(CONFIG.STORAGE_KEY, JSON.stringify(entries));
    } catch (e) {
      console.warn("Local storage write error:", e);
    }
  }
};

