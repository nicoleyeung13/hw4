/**
 * Updates UI based on whether user is signed in or signed out.
 */
function updateAuthUI(user) {
  if (user) {
    // Show signed-in state, hide signed-out button
    elements.authSignedOut.style.display = "none";
    elements.authSignedIn.style.display = "flex";

    // Set name
    const displayName = user.displayName || user.email?.split("@")[0] || "Friend";
    elements.userName.textContent = displayName;

    // Set avatar if present
    if (user.photoURL) {
      elements.userAvatar.src = user.photoURL;
      elements.userAvatar.alt = displayName;
      elements.userAvatar.style.display = "inline-block";
    } else {
      elements.userAvatar.style.display = "none";
    }

    // Auto-fill nickname if field is currently blank
    if (!elements.nicknameInput.value.trim() && displayName) {
      elements.nicknameInput.value = displayName;
    }
  } else {
    // Show signed-out button, hide signed-in state
    elements.authSignedOut.style.display = "flex";
    elements.authSignedIn.style.display = "none";
    elements.userAvatar.src = "";
    elements.userName.textContent = "";
  }
}

/**
 * Trigger Google Sign In popup.
 */
async function handleGoogleSignIn() {
  if (!auth) {
    showFeedback("Authentication service is not loaded.", "error");
    return;
  }

  const provider = new firebase.auth.GoogleAuthProvider();
  try {
    await auth.signInWithPopup(provider);
    showFeedback("Signed in with Google! Welcome.", "success");
  } catch (error) {
    console.error("Google sign-in error:", error);
    if (error.code === "auth/unauthorized-domain") {
      showFeedback(
        `Domain "${window.location.hostname}" is not authorized. Please add "${window.location.hostname}" in Firebase Console > Authentication > Settings > Authorized domains.`,
        "error"
      );
    } else if (error.code !== "auth/popup-closed-by-user") {
      showFeedback(error.message || "Could not sign in with Google.", "error");
    }
  }
}

/**
 * Trigger Sign Out.
 */
async function handleSignOut() {
  if (!auth) return;
  try {
    await auth.signOut();
    showFeedback("Signed out.", "success");
  } catch (error) {
    console.error("Sign-out error:", error);
  }
}

