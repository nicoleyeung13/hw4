// 9. EVENT HANDLERS
// ============================================================================

async function handleTurnSubmit(event) {
  event.preventDefault();
  clearFeedback();

  const name = elements.nicknameInput.value.trim();
  const answer = elements.answerInput.value.trim();
  const nextQuestion = elements.nextQuestionInput.value.trim();

  // Validate fields
  if (!name || !answer || !nextQuestion) {
    showFeedback("Please fill in your nickname, answer, and a question for the next person.", "error");
    return;
  }

  // Ensure user is signed in if auth is available
  if (auth && !currentUser) {
    showFeedback("Please sign in with Google above before passing your turn on.", "error");
    return;
  }

  const activeQuestion = getCurrentQuestion().text;

  // Build record including Google Auth metadata if signed in
  const newEntry = {
    name: name,
    question: activeQuestion,
    answer: answer,
    nextQuestion: nextQuestion,
    timestamp: new Date().toISOString(),
    userId: currentUser ? currentUser.uid : null,
    userPhoto: currentUser ? currentUser.photoURL : null
  };

  elements.submitBtn.disabled = true;
  elements.submitBtn.textContent = "Passing it on...";

  try {
    const result = await JournalStorage.saveEntry(newEntry);

    if (result.success) {
      elements.turnForm.reset();

      // If user is logged in, re-populate nickname for their convenience
      if (currentUser?.displayName) {
        elements.nicknameInput.value = currentUser.displayName;
      }

      showFeedback("Your turn has been passed on! Thank you.", "success");

      if (!db) {
        state.entries.push(newEntry);
        state.historyIndex = state.entries.length - 1;
        renderCurrentQuestion();
        renderHistory();
      }
    } else {
      showFeedback(result.error || "Failed to save your turn. Please try again.", "error");
    }
  } catch (err) {
    console.error("Submission error:", err);
    showFeedback("An unexpected error occurred while saving.", "error");
  } finally {
    elements.submitBtn.disabled = false;
    elements.submitBtn.textContent = "Pass it on";
  }
}

function handlePrevClick() {
  if (state.historyIndex > 0) {
    state.historyIndex -= 1;
    renderHistory();
  }
}

function handleNextClick() {
  if (state.historyIndex < state.entries.length - 1) {
    state.historyIndex += 1;
    renderHistory();
  }
}

// ============================================================================
// 10. INITIALIZATION
// ============================================================================

function init() {
  console.log(`[App Init] Initializing journal. Firebase ProjectId: "${firebaseConfig.projectId}"`);

  // Event listeners for forms and pagination
  elements.turnForm.addEventListener("submit", handleTurnSubmit);
  elements.prevBtn.addEventListener("click", handlePrevClick);
  elements.nextBtn.addEventListener("click", handleNextClick);

  // Event listeners for Authentication
  if (elements.googleSignInBtn) {
    elements.googleSignInBtn.addEventListener("click", handleGoogleSignIn);
  }
  if (elements.signOutBtn) {
    elements.signOutBtn.addEventListener("click", handleSignOut);
  }

  // Render initial static view
  renderCurrentQuestion();
  renderHistory();

  // Listen for Google Auth state changes
  if (auth) {
    auth.onAuthStateChanged((user) => {
      currentUser = user;
      updateAuthUI(user);

      if (user) {
        console.log(`[Auth State] User signed in: ${user.displayName || user.email} (UID: ${user.uid})`);
        clearFeedback();

        // Start Firestore listener ONLY after confirming user is signed in
        if (!activeUnsubscribe) {
          activeUnsubscribe = JournalStorage.subscribe((updatedEntries) => {
            const previousTotal = state.entries.length;
            state.entries = updatedEntries;

            if (updatedEntries.length > previousTotal) {
              state.historyIndex = updatedEntries.length - 1;
            }

            renderCurrentQuestion();
            renderHistory();
          });
        }
      } else {
        console.log("[Auth State] User signed out (null). Halting Firestore queries.");
        // Cancel active Firestore listener to prevent permission-denied errors
        if (activeUnsubscribe) {
          activeUnsubscribe();
          activeUnsubscribe = null;
        }
        state.entries = [];
        renderCurrentQuestion();
        renderHistory();
      }
    });
  } else {
    // Fallback if auth is unavailable: load local storage directly
    JournalStorage.subscribe((updatedEntries) => {
      state.entries = updatedEntries;
      renderCurrentQuestion();
      renderHistory();
    });
  }
}

document.addEventListener("DOMContentLoaded", init);
