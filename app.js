// 7. HELPER FUNCTIONS
// ============================================================================

function getCurrentQuestion() {
  if (state.entries.length > 0) {
    const latestEntry = state.entries[state.entries.length - 1];
    return {
      text: latestEntry.nextQuestion,
      author: latestEntry.name
    };
  }
  return {
    text: CONFIG.DEFAULT_QUESTION,
    author: null
  };
}

function formatTimestamp(timestamp) {
  const date = new Date(timestamp);
  return date.toLocaleDateString(undefined, {
    month: "short",
    day: "numeric",
    year: "numeric"
  }) + " • " + date.toLocaleTimeString(undefined, {
    hour: "numeric",
    minute: "2-digit"
  });
}

function escapeHTML(str) {
  const div = document.createElement("div");
  div.textContent = str || "";
  return div.innerHTML;
}

// ============================================================================
// 8. UI RENDERING
// ============================================================================

function renderCurrentQuestion() {
  const current = getCurrentQuestion();
  elements.currentQuestionDisplay.textContent = current.text;

  if (current.author) {
    elements.currentQuestionOrigin.textContent = `Left by ${current.author} for whoever came next.`;
  } else {
    elements.currentQuestionOrigin.textContent = "The original prompt to start our circle.";
  }
}

function renderHistory() {
  // If user is not authenticated and auth is active, do not attempt to read entries
  if (!currentUser && auth) {
    elements.historyCounter.textContent = "Sign in required";
    elements.historyEntryContainer.innerHTML = `
      <div class="history-empty-state">
        <p>Please sign in with Google below to view and pass on questions in our shared journal.</p>
      </div>
    `;
    elements.prevBtn.disabled = true;
    elements.nextBtn.disabled = true;
    return;
  }

  const total = state.entries.length;

  if (total === 0) {
    elements.historyCounter.textContent = "0 entries";
    elements.historyEntryContainer.innerHTML = `
      <div class="history-empty-state">
        <p>No entries yet. Be the first to answer the question above and pass it on!</p>
      </div>
    `;
    elements.prevBtn.disabled = true;
    elements.nextBtn.disabled = true;
    return;
  }

  if (state.historyIndex < 0) {
    state.historyIndex = 0;
  } else if (state.historyIndex >= total) {
    state.historyIndex = total - 1;
  }

  elements.historyCounter.textContent = `Entry ${state.historyIndex + 1} of ${total}`;

  const entry = state.entries[state.historyIndex];

  // Optional avatar display for entries made by authenticated friends
  const authorAvatarHTML = entry.userPhoto
    ? `<img src="${entry.userPhoto}" class="history-avatar" alt="" />`
    : "";

  elements.historyEntryContainer.innerHTML = `
    <div class="history-meta">
      <span class="history-author">
        ${authorAvatarHTML}
        <span>${escapeHTML(entry.name)}</span>
      </span>
      <time class="history-date">${formatTimestamp(entry.timestamp)}</time>
    </div>

    <div class="history-question">
      <span class="history-label">Question answered</span>
      <p class="history-question-text">“${escapeHTML(entry.question)}”</p>
    </div>

    <div class="history-answer">
      <span class="history-label">Answer</span>
      <p class="history-answer-text">${escapeHTML(entry.answer)}</p>
    </div>

    <div class="history-next-question">
      <span class="history-label">Question passed forward</span>
      <p class="history-next-text">“${escapeHTML(entry.nextQuestion)}”</p>
    </div>
  `;

  elements.prevBtn.disabled = state.historyIndex <= 0;
  elements.nextBtn.disabled = state.historyIndex >= total - 1;
}

function showFeedback(message, type = "error") {
  elements.formFeedback.textContent = message;
  elements.formFeedback.className = `form-feedback is-${type}`;
  elements.formFeedback.style.display = "block";

  if (type === "success") {
    setTimeout(() => {
      elements.formFeedback.style.display = "none";
    }, 4500);
  }
}

function clearFeedback() {
  elements.formFeedback.textContent = "";
  elements.formFeedback.style.display = "none";
  elements.formFeedback.className = "form-feedback";
}

